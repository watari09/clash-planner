export let LANG = (() => {
  try {
    const saved = localStorage.getItem(STORE_LANG);
    if (saved === 'de' || saved === 'en') return saved;
  } catch { /* kein localStorage (Node-Tests) */ }
  const nav = globalThis.navigator?.language || 'de';
  return nav.toLowerCase().startsWith('de') ? 'de' : 'en';
})();

export function setLang(lang) {
  LANG = lang === 'en' ? 'en' : 'de';
  try { localStorage.setItem(STORE_LANG, LANG); } catch { /* egal */ }
  document.documentElement.lang = LANG;
}

/** Locale für Datum und Zahlen. */
export const locale = () => (LANG === 'de' ? 'de-DE' : (globalThis.navigator?.language?.startsWith('en') ? navigator.language : 'en-GB'));

/** Übersetzt einen deutschen Text und setzt Platzhalter ein. */
export function t(de, vars = {}) {
  const text = LANG === 'en' ? (EN[de] ?? de) : de;
  return text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
